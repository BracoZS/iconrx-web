import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { downloadIcon, listIcons } from "iconrx";

/** @typedef {{ attrs: Record<string, string>, innerHTML: string }} IconData */

/** @type {IconData} */
export const FALLBACK_ICON = {
  attrs: {
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "red",
    "stroke-width": "2",
    "stroke-linecap": "round",
    "stroke-linejoin": "round",
  },
  innerHTML: `<circle cx="12" cy="12" r="10"/><line x1="12" x2="12" y1="8" y2="12"/><line x1="12" x2="12.01" y1="16" y2="16"/>`,
};

// Root <svg> attributes worth keeping. width/height are dropped: the component sets the size.
const KEPT_ATTRS = new Set([
  "viewBox",
  "fill",
  "stroke",
  "stroke-width",
  "stroke-linecap",
  "stroke-linejoin",
  "fill-rule",
  "clip-rule",
]);

const TYPES_FILE = fileURLToPath(new URL("./types.generated.d.ts", import.meta.url));

/** @param {string} raw @returns {IconData} */
export function parseSvg(raw) {
  const svg = raw.replace(/<\?xml[\s\S]*?\?>|<!DOCTYPE[\s\S]*?>|<!--[\s\S]*?-->/gi, "").trim();
  const tagAttrs = svg.match(/<svg\b([^>]*)>/i)?.[1] ?? "";
  /** @type {Record<string, string>} */
  const attrs = {};

  for (const [, key, dq, sq] of tagAttrs.matchAll(/([\w:.-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g)) {
    const name = key.toLowerCase() === "viewbox" ? "viewBox" : key;
    if (KEPT_ATTRS.has(name)) attrs[name] = dq ?? sq ?? "";
  }

  attrs.viewBox ??= "0 0 24 24";
  // Outline icons (with stroke) get fill="none"; everything else inherits the text color.
  attrs.fill ??= attrs.stroke ? "none" : "currentColor";

  return { attrs, innerHTML: svg.replace(/<\/?svg\b[^>]*>/gi, "").trim() };
}

/** @returns {Record<string, IconData>} */
export function loadIcons(/** @type {string} */ absDir) {
  return Object.fromEntries(
    listIcons(absDir).map((name) => [
      name,
      parseSvg(fs.readFileSync(path.join(absDir, `${name}.svg`), "utf-8")),
    ])
  );
}

/** @type {Map<string, Promise<IconData | null>>} */
const autoFetchCache = new Map();

/**
 * Dev-only: downloads a missing icon once per name. Never throws.
 * @param {string} absDir
 * @param {string} name
 * @param {string} set
 */
export function autoFetchIcon(absDir, name, set) {
  let pending = autoFetchCache.get(name);
  if (!pending) {
    pending = downloadIcon(absDir, name, { set }).then(
      (r) => {
        console.log(`[iconrx] ✓ Downloaded "${r.collection}:${r.icon}" -> ${r.localName}.svg`);
        return parseSvg(r.svg);
      },
      () => null
    );
    autoFetchCache.set(name, pending);
  }
  return pending;
}

/** Regenerates the `IconName` union used for autocomplete. */
export function writeTypes(/** @type {string} */ absDir) {
  const names = listIcons(absDir);
  const union = names.length ? names.map((n) => JSON.stringify(n)).join(" | ") : "string";
  const content = `// Auto-generated by astro-iconrx\nexport type IconName = ${union};\n`;

  try {
    if (!fs.existsSync(TYPES_FILE) || fs.readFileSync(TYPES_FILE, "utf-8") !== content) {
      fs.writeFileSync(TYPES_FILE, content);
    }
  } catch {
    // Read-only install: skip type generation.
  }
}
