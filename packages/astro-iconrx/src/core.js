import fs from "node:fs";
import path from "node:path";
import { downloadIcon, listIcons } from "iconrx";

/** @typedef {{ attrs: Record<string, string>, innerHTML: string }} IconData */

/** @type {IconData} */
export const FALLBACK_ICON = {
  attrs: {
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "red",
    "stroke-width": "2",
    "stroke-linecap": "round",
    "stroke-linejoin": "round",
  },
  innerHTML: `<circle cx="12" cy="12" r="10"/><line x1="12" x2="12" y1="8" y2="12"/><line x1="12" x2="12.01" y1="16" y2="16"/>`,
};

// Root <svg> attributes worth keeping. width/height are dropped: the component sets the size.
const KEPT_ATTRS = new Set([
  "viewBox",
  "fill",
  "stroke",
  "stroke-width",
  "stroke-linecap",
  "stroke-linejoin",
  "fill-rule",
  "clip-rule",
]);

const FAILED_CACHE_TTL_MS = 5000;

/** @param {string} raw @returns {IconData} */
export function parseSvg(raw) {
  const svg = raw.replace(/<\?xml[\s\S]*?\?>|<!DOCTYPE[\s\S]*?>|<!--[\s\S]*?-->/gi, "").trim();
  const openTag = svg.match(/<svg\b([^>]*)>/i);
  const tagAttrs = openTag?.[1] ?? "";
  /** @type {Record<string, string>} */
  const attrs = {};

  for (const [, key, dq, sq] of tagAttrs.matchAll(/([\w:.-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g)) {
    const name = key.toLowerCase() === "viewbox" ? "viewBox" : key;
    if (KEPT_ATTRS.has(name)) attrs[name] = dq ?? sq ?? "";
  }

  attrs.viewBox ??= "0 0 24 24";
  // Outline icons (with stroke) get fill="none"; everything else inherits the text color.
  attrs.fill ??= attrs.stroke ? "none" : "currentColor";

  const innerHTML = openTag
    ? svg
        .slice((openTag.index ?? 0) + openTag[0].length)
        .replace(/<\/svg>\s*$/i, "")
        .trim()
    : "";

  return { attrs, innerHTML };
}

/** @returns {Record<string, IconData>} */
export function loadIcons(/** @type {string} */ absDir) {
  return Object.fromEntries(
    listIcons(absDir).map((name) => [
      name,
      parseSvg(fs.readFileSync(path.join(absDir, `${name}.svg`), "utf-8")),
    ])
  );
}

/** @type {Map<string, Promise<IconData | null>>} */
const autoFetchCache = new Map();

/** Clears cached auto-fetch entries (called when local .svg files are removed). */
export function clearAutoFetchCache() {
  autoFetchCache.clear();
}

/**
 * Dev-only: downloads a missing icon once per name. Never throws.
 * Failed lookups expire after a short TTL so transient network errors can recover.
 * @param {string} absDir
 * @param {string} name
 * @param {string} set
 */
export function autoFetchIcon(absDir, name, set) {
  let pending = autoFetchCache.get(name);
  if (!pending) {
    pending = downloadIcon(absDir, name, { set }).then(
      (r) => {
        console.log(`[iconrx] ✓ Downloaded "${r.collection}:${r.icon}" -> ${r.localName}.svg`);
        return parseSvg(r.svg);
      },
      () => {
        const timer = setTimeout(() => autoFetchCache.delete(name), FAILED_CACHE_TTL_MS);
        timer.unref?.();
        return null;
      }
    );
    autoFetchCache.set(name, pending);
  }
  return pending;
}

/**
 * Builds the TypeScript module-augmentation content for `astro-iconrx`.
 * Includes both `"set/name"` and `"set:name"` for single-level subfolder icons.
 * @param {string} absDir
 */
export function buildTypesContent(absDir) {
  const keys = new Set();
  for (const name of listIcons(absDir)) {
    keys.add(name);
    const slash = name.indexOf("/");
    if (slash !== -1 && slash === name.lastIndexOf("/")) {
      keys.add(name.replace("/", ":"));
    }
  }

  const entries = [...keys]
    .sort()
    .map((name) => `    ${JSON.stringify(name)}: true;`)
    .join("\n");

  return [
    "// Auto-generated by astro-iconrx — do not edit.",
    'declare module "astro-iconrx" {',
    "  interface IconRegistry {",
    ...(entries ? [entries] : []),
    "  }",
    "}",
    "",
    "export {};",
    "",
  ].join("\n");
}

/**
 * Writes generated types to `filePath` (inside the user's `.astro/` directory) if changed.
 * @param {string} filePath
 * @param {string} absDir
 */
export function writeTypesFile(filePath, absDir) {
  const content = buildTypesContent(absDir);
  try {
    if (!fs.existsSync(filePath) || fs.readFileSync(filePath, "utf-8") !== content) {
      fs.mkdirSync(path.dirname(filePath), { recursive: true });
      fs.writeFileSync(filePath, content, "utf-8");
    }
  } catch {
    // Ignore write errors on read-only filesystems.
  }
}
